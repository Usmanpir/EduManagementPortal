import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { Badge } from "@/components/ui/badge";
import { METHOD_LABELS } from "@/components/finance/finance-ui";
import { PrintHeader } from "@/components/print/print-header";
import { requirePageContext } from "@/server/auth/context";
import { receiptDocument } from "@/server/modules/finance/payments";
import { formatDate, formatMoney } from "@/lib/format";

export const metadata: Metadata = { title: "Receipt" };

const UUID = /^[0-9a-f-]{36}$/i;

export default async function PrintReceipt({ params }: PageProps<"/finance/print/receipt/[id]">) {
  const ctx = await requirePageContext("payments.view");
  const { id } = await params;
  const r = UUID.test(id) ? await receiptDocument(ctx, id) : null;
  if (!r) notFound();
  const org = await ctx.db.organization.findUniqueOrThrow({ where: { id: ctx.orgId }, select: { name: true, address: true, phone: true, email: true } });
  const money = (v: number) => formatMoney(v, ctx.organization.currency);
  const rows: [string, React.ReactNode][] = [
    ["Received from", `${r.student.name} (Adm. ${r.student.admissionNo}${r.student.className ? `, ${r.student.className}` : ""})`],
    ["For", `${r.invoice.title} · ${r.invoice.invoiceNo}`],
    ["Date", formatDate(r.paidAt, "long")],
    ["Method", `${METHOD_LABELS[r.method]}${r.reference ? ` · ${r.reference}` : ""}`],
    ["Received by", r.receivedBy ?? "—"],
    ["Balance remaining", money(r.invoice.balance)],
  ];

  return (
    <article className="mx-auto max-w-xl text-small">
      <PrintHeader organization={org} title="Receipt" subtitle={r.receiptNo} meta={r.status === "VOIDED" ? <Badge variant="danger" className="mt-1">Voided</Badge> : undefined} />
      <div className="mb-6 rounded-xl border bg-success-subtle/40 p-5 text-center print:bg-transparent">
        <p className="text-caption tracking-wide text-muted-foreground uppercase">Amount received</p>
        <p className="tabular text-display font-semibold">{money(r.amount)}</p>
      </div>
      <dl className="divide-y">
        {rows.map(([k, v]) => (
          <div key={k} className="flex justify-between gap-4 py-2">
            <dt className="text-muted-foreground">{k}</dt>
            <dd className="text-end font-medium">{v}</dd>
          </div>
        ))}
      </dl>
      {r.voidReason && <p className="mt-4 text-danger-foreground">Voided: {r.voidReason}</p>}
      <p className="mt-10 text-center text-caption text-muted-foreground">This receipt was generated by {org.name}&apos;s school system and is valid without a signature.</p>
    </article>
  );
}
