import { z } from "zod";
import { isoDate, optionalText, optionalUuid, uuid } from "./common";

export const FEE_CATEGORIES = ["TUITION", "ADMISSION", "EXAM", "TRANSPORT", "HOSTEL", "LIBRARY", "LAB", "FINE", "OTHER"] as const;
export const FEE_FREQUENCIES = ["MONTHLY", "QUARTERLY", "ANNUAL", "ONE_TIME"] as const;
export const PAYMENT_METHODS = ["CASH", "BANK_TRANSFER", "CARD", "CHEQUE", "ONLINE", "MOBILE_WALLET", "OTHER"] as const;
/** Categories a student must opt into (not everyone uses the van or hostel). */
export const OPT_IN_CATEGORIES = ["TRANSPORT", "HOSTEL"] as const;

const money = (label: string) =>
  z.coerce
    .number({ error: `${label} must be a number.` })
    .min(0, `${label} can't be negative.`)
    .max(100_000_000, `${label} is too large.`)
    .transform((v) => Math.round(v * 100) / 100);

export const feeStructureSchema = z.object({
  name: z.string().trim().min(1, "Name is required.").max(80),
  category: z.enum(FEE_CATEGORIES),
  amount: money("Amount").refine((v) => v > 0, "Amount must be more than zero."),
  frequency: z.enum(FEE_FREQUENCIES),
  dueDay: z.coerce.number().int().min(1).max(28),
  classId: optionalUuid,
  campusId: optionalUuid,
  isActive: z.boolean().default(true),
});

export const studentFeeSchema = z.object({
  feeStructureId: uuid,
  isActive: z.boolean(),
  discountType: z.enum(["NONE", "PERCENT", "FIXED"]),
  discountValue: money("Discount"),
  discountReason: optionalText(120),
});

export const generateInvoicesSchema = z.object({
  billingPeriod: z.string().regex(/^\d{4}-(0[1-9]|1[0-2])$/, "Choose a month."),
  issueDate: isoDate,
  dueDate: isoDate,
  classId: optionalUuid,
  feeStructureIds: z.array(uuid).min(1, "Choose at least one fee.").max(30),
});

export const invoiceSchema = z.object({
  studentId: uuid,
  title: z.string().trim().min(1, "Title is required.").max(120),
  issueDate: isoDate,
  dueDate: isoDate,
  notes: optionalText(500),
  items: z
    .array(z.object({ description: z.string().trim().min(1, "Describe the item.").max(120), category: z.enum(FEE_CATEGORIES), amount: money("Amount").refine((v) => v > 0, "Amount must be more than zero."), discount: money("Discount").default(0) }))
    .min(1, "Add at least one item.")
    .max(30),
});

export const paymentSchema = z.object({
  invoiceId: uuid,
  amount: money("Amount").refine((v) => v > 0, "Enter the amount received."),
  method: z.enum(PAYMENT_METHODS),
  reference: optionalText(80),
  paidAt: isoDate,
  notes: optionalText(300),
  /** Generated by the client once per form; retries with the same key never double-charge. */
  idempotencyKey: z.string().min(8).max(80),
});

export const voidPaymentSchema = z.object({ reason: z.string().trim().min(3, "Give a reason for voiding.").max(200) });
